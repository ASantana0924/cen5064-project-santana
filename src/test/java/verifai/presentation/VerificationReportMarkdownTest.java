package verifai.presentation;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.Arrays;
import java.util.List;

import org.junit.jupiter.api.Test;

import verifai.data.InMemoryTaskRepository;
import verifai.data.TaskRepository;
import verifai.domain.Task;
import verifai.domain.VerificationType;
import verifai.service.ReportService;
import verifai.service.VerificationReport;

class VerificationReportMarkdownTest {

    private static final Instant NOW = Instant.parse("2026-11-22T14:03:27Z");

    private final TaskRepository repository = new InMemoryTaskRepository();
    private final ReportService reports = new ReportService(repository, Clock.fixed(NOW, ZoneOffset.UTC));

    private VerificationReport reportOf(Task task) {
        return reports.getReport(repository.save(task).getId());
    }

    private static Task startedTask(String title) {
        Task task = new Task(title, "Lock an account after 5 failed logins.", "sam");
        task.addRequirement("Count failed logins per account", "sam");
        task.addRequirement("Reset the count after a successful login", "sam");
        task.addAcceptanceCriterion("The sixth failed login is refused", "sam");
        task.start("sam");
        return task;
    }

    private static Task approvedTask() {
        Task task = startedTask("Rate limit login attempts");
        task.recordTestRun("JUnit", 3, 2, 0, "Before any artifact", "sam");
        task.recordArtifact("Write a rate limiter", "Claude", "class LoginRateLimiter {}", "sam");
        task.recordArtifact("Make it thread-safe", "ChatGPT", "class LoginRateLimiter {\n    // v2\n}", "sam");
        task.recordTestRun("JUnit", 8, 8, 0, "All pass", "sam");
        for (VerificationType type : VerificationType.values()) {
            task.markCheckPassed(type, "Reviewed " + type.name().toLowerCase(), "dana");
        }
        task.approve("alex");
        task.approve("dana");
        return task;
    }

    private String render(Task task) {
        return VerificationReportMarkdown.render(reportOf(task));
    }

    /** The text from a heading up to the next heading of the same or a higher level. */
    private static String section(String markdown, String heading) {
        int start = markdown.indexOf("\n" + heading + "\n");
        assertTrue(start >= 0, "Missing heading " + heading);
        int end = markdown.indexOf("\n## ", start + heading.length() + 2);
        return markdown.substring(start + 1, end < 0 ? markdown.length() : end);
    }

    private static List<String> lines(String text) {
        return Arrays.asList(text.split("\n"));
    }

    @Test
    void theReportHasEverySectionInOrder() {
        String markdown = render(approvedTask());

        List<String> headings = lines(markdown).stream().filter(line -> line.startsWith("## ")).toList();
        assertEquals(List.of("## Description", "## Requirements", "## Acceptance criteria", "## Checks", "## Test runs",
                "## Artifact versions", "## Approvals", "## Audit history"), headings);
        assertTrue(markdown.startsWith("# Verification report: Rate limit login attempts\n\n"));
        assertTrue(markdown.endsWith("\n") && !markdown.endsWith("\n\n"));
    }

    @Test
    void theSummaryShowsStatusOwnerApprovalsChecksAndTheTaskId() {
        Task task = approvedTask();
        String markdown = render(task);

        assertTrue(markdown.contains("Generated by VerifAI on 2026-11-22 14:03 UTC.\n"));
        assertTrue(markdown.contains("""
                - **Status:** Approved
                - **Owner:** sam
                - **Approvals:** 2 of 2 approvals
                - **Checks:** 6 passed, 0 failed, 0 pending
                - **Task ID:** %s
                """.formatted(task.getId())));
    }

    @Test
    void theReportOfAnApprovedTaskListsBothApprovers() {
        String approvals = section(render(approvedTask()), "## Approvals");

        assertTrue(approvals.contains("2 of 2 approvals."));
        List<String> rows = lines(approvals).stream().filter(line -> line.startsWith("| ") && !line.startsWith("| ---")).toList();
        assertEquals("| Developer | Approved |", rows.get(0));
        assertTrue(rows.get(1).startsWith("| alex | 2026-"), rows.get(1));
        assertTrue(rows.get(2).startsWith("| dana | 2026-"), rows.get(2));
        assertEquals(3, rows.size());
    }

    @Test
    void requirementsAndCriteriaAreNumberedLists() {
        String markdown = render(approvedTask());

        assertTrue(section(markdown, "## Requirements").contains(
                "1. Count failed logins per account\n2. Reset the count after a successful login\n"));
        assertTrue(section(markdown, "## Acceptance criteria").contains("1. The sixth failed login is refused\n"));
    }

    @Test
    void eachCheckShowsEvidenceWhenPassedAndNotesWhenFailed() {
        Task task = startedTask("Rate limit login attempts");
        task.markCheckPassed(VerificationType.REQUIREMENTS, "Matches both requirements", "dana");
        task.markCheckFailed(VerificationType.TESTING, "No test for the lockout window", "alex");

        String checks = section(render(task), "## Checks");

        assertTrue(checks.contains("1 passed, 1 failed, 4 pending."));
        List<String> rows = lines(checks).stream().filter(line -> line.startsWith("| ") && !line.startsWith("| ---")).toList();
        assertEquals("| Check | Status | Reviewer | Reviewed on | Evidence or notes |", rows.get(0));
        assertTrue(rows.get(1).matches("\\| Requirements \\| Passed \\| dana \\| \\d{4}-\\d{2}-\\d{2} "
                + "\\| Evidence: Matches both requirements \\|"), rows.get(1));
        assertTrue(rows.get(3).matches("\\| Testing \\| Failed \\| alex \\| \\d{4}-\\d{2}-\\d{2} "
                + "\\| Notes: No test for the lockout window \\|"), rows.get(3));
        assertEquals("| Security | Pending | — | — | — |", rows.get(6));
        assertEquals(7, rows.size());
    }

    @Test
    void testRunsAreListedOldestFirstWithTheirArtifactVersion() {
        List<String> rows = lines(section(render(approvedTask()), "## Test runs")).stream()
                .filter(line -> line.startsWith("| 2026") || line.matches("\\| \\d{4}-.*"))
                .toList();

        assertEquals(2, rows.size());
        assertTrue(rows.get(0).endsWith("| sam | JUnit | 3 | 2 | 0 | 1 | none | Before any artifact |"), rows.get(0));
        assertTrue(rows.get(1).endsWith("| sam | JUnit | 8 | 8 | 0 | 0 | 2 | All pass |"), rows.get(1));
    }

    @Test
    void artifactVersionsAreNewestFirstWithTheirPromptAndCodeAsRecorded() {
        String artifacts = section(render(approvedTask()), "## Artifact versions");

        int version2 = artifacts.indexOf("### Version 2 (latest)");
        int version1 = artifacts.indexOf("### Version 1\n");
        assertTrue(version2 >= 0 && version1 > version2, artifacts);
        assertTrue(artifacts.contains("""
                - **AI tool:** ChatGPT
                - **Recorded by:** sam on 2026-"""));
        assertTrue(artifacts.contains("**Prompt**\n\n```text\nMake it thread-safe\n```\n"));
        assertTrue(artifacts.contains("**Code**\n\n```\nclass LoginRateLimiter {\n    // v2\n}\n```\n"));
    }

    @Test
    void aTaskWithNoArtifactsSaysSoInEveryEmptySection() {
        String markdown = render(new Task("Add password reset email", "", "alex"));

        assertTrue(markdown.contains("- **Status:** Draft\n"));
        assertTrue(section(markdown, "## Description").contains("_No description._"));
        assertTrue(section(markdown, "## Requirements").contains("_No requirements._"));
        assertTrue(section(markdown, "## Acceptance criteria").contains("_No acceptance criteria._"));
        assertTrue(section(markdown, "## Checks").contains("0 passed, 0 failed, 6 pending."));
        assertTrue(section(markdown, "## Test runs").contains("_No test runs recorded._"));
        assertTrue(section(markdown, "## Artifact versions").contains("_No artifacts recorded._"));
        String approvals = section(markdown, "## Approvals");
        assertTrue(approvals.contains("0 of 2 approvals."));
        assertFalse(approvals.contains("| Developer |"));
        assertTrue(section(markdown, "## Audit history").contains("| Task created | alex | Title: Add password reset email |"));
    }

    @Test
    void pipesAndLineBreaksInTypedTextStayInsideTheirTableCell() {
        Task task = startedTask("Rate limit login attempts");
        task.markCheckFailed(VerificationType.SECURITY, "Uses a | b\nand <b>bold</b> *markup*", "alex");

        String row = lines(section(render(task), "## Checks")).stream()
                .filter(line -> line.startsWith("| Security"))
                .findFirst()
                .orElseThrow();

        assertTrue(row.endsWith("| Notes: Uses a \\| b<br>and \\<b\\>bold\\</b\\> \\*markup\\* |"), row);
    }

    @Test
    void markdownInTheTitleAndInListItemsShowsAsWritten() {
        Task task = new Task("Fix #61: escape `code` and [links]", "", "alex");
        task.addRequirement("- starts like a bullet", "alex");
        task.addRequirement("2. starts like a number", "alex");

        String markdown = render(task);

        assertTrue(markdown.startsWith("# Verification report: Fix \\#61: escape \\`code\\` and \\[links\\]\n"));
        assertTrue(markdown.contains("1. \\- starts like a bullet\n2. 2\\. starts like a number\n"));
    }

    @Test
    void underscoresInsideWordsStayAsTheyAreAndOthersAreEscaped() {
        Task task = new Task("Rename code_quality and __init__ to _private_", "", "alex");

        assertTrue(render(task).startsWith(
                "# Verification report: Rename code_quality and \\_\\_init\\_\\_ to \\_private\\_\n"));
    }

    @Test
    void aDescriptionKeepsItsLineBreaks() {
        Task task = new Task("Add login check", "First line.\nSecond line.", "alex");

        assertTrue(section(render(task), "## Description").contains("First line.  \nSecond line."));
    }

    @Test
    void codeContainingBackticksGetsALongerFence() {
        Task task = startedTask("Rate limit login attempts");
        task.recordArtifact("Write docs", "Claude", "Example:\n```java\nint x = 1;\n```", "sam");

        String artifacts = section(render(task), "## Artifact versions");

        assertTrue(artifacts.contains("**Code**\n\n````\nExample:\n```java\nint x = 1;\n```\n````\n"), artifacts);
    }

    @Test
    void theFileNameIsTheTitleInLowercaseWithTheReportDate() {
        assertEquals("verifai-report-rate-limit-login-attempts-2026-11-22.md",
                VerificationReportMarkdown.fileName(reportOf(new Task("Rate limit login attempts", "", "sam"))));
        assertEquals("verifai-report-cafe-menu-v2-2026-11-22.md",
                VerificationReportMarkdown.fileName(reportOf(new Task("  Café menu: v2! ", "", "sam"))));
    }

    @Test
    void aLongTitleIsCutAtAWordToSixtyCharacters() {
        String title = "Replace the password hashing scheme with bcrypt and migrate every existing account safely";

        String name = VerificationReportMarkdown.fileName(reportOf(new Task(title, "", "sam")));

        // "...-and-migrate" is 59 characters; adding "-every" would pass 60.
        assertEquals("verifai-report-replace-the-password-hashing-scheme-with-bcrypt-and-migrate-2026-11-22.md", name);
    }

    @Test
    void aTitleWithNoLettersOrDigitsFallsBackToTheTaskId() {
        Task task = new Task("???", "", "sam");

        String name = VerificationReportMarkdown.fileName(reportOf(task));

        assertEquals("verifai-report-task-" + task.getId().toString().substring(0, 8) + "-2026-11-22.md", name);
    }
}
