-- VerifAI schema: one Task aggregate (ADR-003) spread over eight tables.
--
-- Rows that belong to a task keep the task's order in a position column
-- (artifacts use their version number). This file uses only SQL that runs on
-- both PostgreSQL and H2, so the tests run the same migration as the app.
--
-- audit_entries, artifacts, and test_runs are append-only: the app inserts new
-- rows and never updates or deletes them (README Rule 9, ADR-007).

CREATE TABLE tasks (
    id                 UUID                        NOT NULL,
    title              TEXT                        NOT NULL,
    description        TEXT                        NOT NULL,
    owner              TEXT                        NOT NULL,
    status             VARCHAR(20)                 NOT NULL,
    required_approvals INTEGER                     NOT NULL,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_tasks PRIMARY KEY (id)
);

CREATE INDEX ix_tasks_created_at ON tasks (created_at);

CREATE TABLE task_requirements (
    task_id  UUID    NOT NULL,
    position INTEGER NOT NULL,
    text     TEXT    NOT NULL,
    CONSTRAINT pk_task_requirements PRIMARY KEY (task_id, position),
    CONSTRAINT fk_task_requirements_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE TABLE task_acceptance_criteria (
    task_id  UUID    NOT NULL,
    position INTEGER NOT NULL,
    text     TEXT    NOT NULL,
    CONSTRAINT pk_task_acceptance_criteria PRIMARY KEY (task_id, position),
    CONSTRAINT fk_task_acceptance_criteria_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

-- One row per check type for every task. Rows are updated in place.
CREATE TABLE checks (
    task_id     UUID        NOT NULL,
    type        VARCHAR(20) NOT NULL,
    status      VARCHAR(20) NOT NULL,
    evidence    TEXT,
    notes       TEXT,
    reviewer    TEXT,
    reviewed_on DATE,
    CONSTRAINT pk_checks PRIMARY KEY (task_id, type),
    CONSTRAINT fk_checks_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

-- Current approvals only. Cleared approvals stay in audit_entries.
CREATE TABLE approvals (
    task_id     UUID                        NOT NULL,
    position    INTEGER                     NOT NULL,
    developer   TEXT                        NOT NULL,
    approved_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_approvals PRIMARY KEY (task_id, position),
    CONSTRAINT fk_approvals_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE TABLE artifacts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id      UUID                        NOT NULL,
    version      INTEGER                     NOT NULL,
    prompt       TEXT                        NOT NULL,
    ai_tool      TEXT                        NOT NULL,
    code_content TEXT                        NOT NULL,
    recorded_by  TEXT                        NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_artifacts PRIMARY KEY (id),
    CONSTRAINT uq_artifacts_task_version UNIQUE (task_id, version),
    CONSTRAINT fk_artifacts_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE TABLE test_runs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id          UUID                        NOT NULL,
    position         INTEGER                     NOT NULL,
    tool             TEXT                        NOT NULL,
    total            INTEGER                     NOT NULL,
    passed           INTEGER                     NOT NULL,
    failed           INTEGER                     NOT NULL,
    summary          TEXT                        NOT NULL,
    recorded_by      TEXT                        NOT NULL,
    recorded_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    artifact_version INTEGER,
    CONSTRAINT pk_test_runs PRIMARY KEY (id),
    CONSTRAINT uq_test_runs_task_position UNIQUE (task_id, position),
    CONSTRAINT fk_test_runs_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);

CREATE TABLE audit_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id     UUID                        NOT NULL,
    position    INTEGER                     NOT NULL,
    event_type  VARCHAR(30)                 NOT NULL,
    developer   TEXT                        NOT NULL,
    details     TEXT                        NOT NULL,
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_audit_entries PRIMARY KEY (id),
    CONSTRAINT uq_audit_entries_task_position UNIQUE (task_id, position),
    CONSTRAINT fk_audit_entries_task FOREIGN KEY (task_id) REFERENCES tasks (id)
);
