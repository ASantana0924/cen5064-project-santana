package verifai.presentation;

import java.text.Normalizer;
import java.time.Instant;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

import verifai.domain.Approval;
import verifai.domain.Artifact;
import verifai.domain.AuditEntry;
import verifai.domain.AuditEventType;
import verifai.domain.TaskItem;
import verifai.domain.TaskStatus;
import verifai.domain.TestRun;
import verifai.domain.Verification;
import verifai.domain.VerificationStatus;
import verifai.domain.VerificationType;
import verifai.service.VerificationReport;

/**
 * Writes a VerificationReport as a Markdown file (UC-18, ADR-012). The file
 * reads well as plain text and when rendered. Every piece of text a developer
 * typed is escaped, so it shows as written and cannot break the layout: a
 * pipe cannot end a table cell, a line break cannot end a list item, and code
 * cannot close its fence early. Times are in UTC, because the server does not
 * know the reader's time zone.
 */
final class VerificationReportMarkdown {

    private static final DateTimeFormatter TIME =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm 'UTC'").withZone(ZoneOffset.UTC);
    private static final DateTimeFormatter DAY = DateTimeFormatter.ISO_LOCAL_DATE.withZone(ZoneOffset.UTC);

    /** Characters that can start Markdown formatting, a link, HTML, or a table cell anywhere in a line. */
    private static final Pattern SPECIAL = Pattern.compile("[\\\\`*\\[\\]<>|~#]");
    /**
     * An underscore can start emphasis only when it is not between two letters or
     * digits, so snake_case names such as code_quality are left as they are.
     */
    private static final Pattern EDGE_UNDERSCORE = Pattern.compile("(?<![\\p{L}\\p{N}])_|_(?![\\p{L}\\p{N}])");
    /** A line that starts like a list item ("- ", "+ ", "1. ", "2) ") would become one. */
    private static final Pattern LIST_MARKER = Pattern.compile("^(\\s*)([-+]|\\d+[.)])(?=\\s|$)");
    private static final String EMPTY_CELL = "—";

    private VerificationReportMarkdown() {
    }

    static String render(VerificationReport report) {
        StringBuilder md = new StringBuilder();
        md.append("# Verification report: ").append(inline(report.title())).append("\n\n");
        md.append("Generated by VerifAI on ").append(time(report.generatedAt())).append(".\n\n");
        md.append("- **Status:** ").append(label(report.status())).append('\n');
        md.append("- **Owner:** ").append(inline(report.owner())).append('\n');
        md.append("- **Approvals:** ").append(approvalProgress(report)).append('\n');
        md.append("- **Checks:** ").append(checkSummary(report.checks())).append('\n');
        md.append("- **Task ID:** ").append(report.taskId()).append("\n\n");

        md.append("## Description\n\n");
        md.append(report.description().isBlank() ? "_No description._" : paragraphs(report.description())).append("\n\n");

        numberedList(md, "Requirements", report.requirements(), "_No requirements._");
        numberedList(md, "Acceptance criteria", report.acceptanceCriteria(), "_No acceptance criteria._");

        md.append("## Checks\n\n");
        md.append(checkSummary(report.checks())).append(".\n\n");
        table(md, List.of("Check", "Status", "Reviewer", "Reviewed on", "Evidence or notes"),
                report.checks().stream().map(VerificationReportMarkdown::checkRow).toList());

        md.append("## Test runs\n\n");
        if (report.testRuns().isEmpty()) {
            md.append("_No test runs recorded._\n\n");
        } else {
            md.append("Oldest first. A test run is evidence for the Testing check and never changes it.\n\n");
            table(md, List.of("Recorded", "By", "Tool", "Total", "Passed", "Failed", "Skipped", "Artifact version",
                    "Summary"), report.testRuns().stream().map(VerificationReportMarkdown::testRunRow).toList());
        }

        artifacts(md, report.artifacts());

        md.append("## Approvals\n\n");
        md.append(approvalProgress(report)).append(".\n\n");
        if (!report.approvals().isEmpty()) {
            table(md, List.of("Developer", "Approved"), report.approvals().stream()
                    .map(VerificationReportMarkdown::approvalRow)
                    .toList());
        }

        md.append("## Audit history\n\n");
        md.append("Oldest first. Entries are never edited or deleted.\n\n");
        table(md, List.of("Time", "Event", "Developer", "Details"), report.auditHistory().stream()
                .map(VerificationReportMarkdown::auditRow)
                .toList());
        return md.toString().stripTrailing() + "\n";
    }

    /**
     * A file name such as {@code verifai-report-rate-limit-login-attempts-2026-11-22.md}:
     * the title in lowercase ASCII letters and digits, at most 60 characters, and the
     * report date in UTC. A title with no usable letters falls back to the task id.
     */
    static String fileName(VerificationReport report) {
        String slug = Normalizer.normalize(report.title(), Normalizer.Form.NFD)
                .replaceAll("\\p{M}", "")
                .toLowerCase(Locale.ROOT)
                .replaceAll("[^a-z0-9]+", "-")
                .replaceAll("^-+|-+$", "");
        if (slug.length() > 60) {
            String cut = slug.substring(0, 60);
            int lastHyphen = cut.lastIndexOf('-');
            slug = (slug.charAt(60) == '-' || lastHyphen < 0 ? cut : cut.substring(0, lastHyphen)).replaceAll("-+$", "");
        }
        if (slug.isEmpty()) {
            slug = "task-" + report.taskId().toString().substring(0, 8);
        }
        return "verifai-report-" + slug + "-" + DAY.format(report.generatedAt()) + ".md";
    }

    private static void numberedList(StringBuilder md, String heading, List<TaskItem> items, String empty) {
        md.append("## ").append(heading).append("\n\n");
        if (items.isEmpty()) {
            md.append(empty).append("\n\n");
            return;
        }
        for (int i = 0; i < items.size(); i++) {
            md.append(i + 1).append(". ").append(inline(items.get(i).text())).append('\n');
        }
        md.append('\n');
    }

    /** Every version, newest first, each with its prompt and code exactly as recorded. */
    private static void artifacts(StringBuilder md, List<Artifact> artifacts) {
        md.append("## Artifact versions\n\n");
        if (artifacts.isEmpty()) {
            md.append("_No artifacts recorded._\n\n");
            return;
        }
        md.append("Newest first. Recording a version resets every check and clears the approvals, "
                + "so the checks and approvals above are for the latest version.\n\n");
        List<Artifact> newestFirst = new ArrayList<>(artifacts);
        newestFirst.sort((a, b) -> Integer.compare(b.getVersion(), a.getVersion()));
        for (Artifact artifact : newestFirst) {
            md.append("### Version ").append(artifact.getVersion());
            if (artifact == newestFirst.get(0)) {
                md.append(" (latest)");
            }
            md.append("\n\n");
            md.append("- **AI tool:** ").append(inline(artifact.getAiTool())).append('\n');
            md.append("- **Recorded by:** ").append(inline(artifact.getRecordedBy()))
                    .append(" on ").append(time(artifact.getCreatedAt())).append("\n\n");
            md.append("**Prompt**\n\n");
            fenced(md, "text", artifact.getPrompt());
            md.append("**Code**\n\n");
            fenced(md, "", artifact.getCodeContent());
        }
    }

    private static List<String> checkRow(Verification check) {
        String evidenceOrNotes = switch (check.getStatus()) {
            case PASSED -> "Evidence: " + inline(check.getEvidence());
            case FAILED -> "Notes: " + inline(check.getNotes());
            case PENDING -> "";
        };
        return List.of(label(check.getType()), label(check.getStatus()), inline(check.getReviewer()),
                check.getReviewedOn() == null ? "" : check.getReviewedOn().toString(), evidenceOrNotes);
    }

    private static List<String> testRunRow(TestRun run) {
        return List.of(time(run.getRecordedAt()), inline(run.getRecordedBy()), inline(run.getTool()),
                String.valueOf(run.getTotal()), String.valueOf(run.getPassed()), String.valueOf(run.getFailed()),
                String.valueOf(run.getSkipped()),
                run.getArtifactVersion() == null ? "none" : String.valueOf(run.getArtifactVersion()),
                inline(run.getSummary()));
    }

    private static List<String> approvalRow(Approval approval) {
        return List.of(inline(approval.getDeveloper()), time(approval.getApprovedAt()));
    }

    private static List<String> auditRow(AuditEntry entry) {
        return List.of(time(entry.getRecordedAt()), label(entry.getEventType()), inline(entry.getDeveloper()),
                inline(entry.getDetails()));
    }

    private static String approvalProgress(VerificationReport report) {
        return report.approvals().size() + " of " + report.requiredApprovals() + " approvals";
    }

    private static String checkSummary(List<Verification> checks) {
        return count(checks, VerificationStatus.PASSED) + " passed, " + count(checks, VerificationStatus.FAILED)
                + " failed, " + count(checks, VerificationStatus.PENDING) + " pending";
    }

    private static long count(List<Verification> checks, VerificationStatus status) {
        return checks.stream().filter(check -> check.getStatus() == status).count();
    }

    private static void table(StringBuilder md, List<String> headers, List<List<String>> rows) {
        md.append("| ").append(String.join(" | ", headers)).append(" |\n");
        md.append('|').append(" --- |".repeat(headers.size())).append('\n');
        for (List<String> row : rows) {
            md.append("| ")
                    .append(row.stream().map(cell -> cell.isEmpty() ? EMPTY_CELL : cell).collect(Collectors.joining(" | ")))
                    .append(" |\n");
        }
        md.append('\n');
    }

    /** Text kept exactly as written, in a fence longer than any run of backticks inside it. */
    private static void fenced(StringBuilder md, String info, String content) {
        String text = content.replace("\r\n", "\n");
        int longestRun = 0;
        Matcher backticks = Pattern.compile("`+").matcher(text);
        while (backticks.find()) {
            longestRun = Math.max(longestRun, backticks.group().length());
        }
        String fence = "`".repeat(Math.max(3, longestRun + 1));
        md.append(fence).append(info).append('\n').append(text);
        if (!text.endsWith("\n")) {
            md.append('\n');
        }
        md.append(fence).append("\n\n");
    }

    /** Text for one table cell or list item: escaped, with line breaks written as {@code <br>}. */
    static String inline(String text) {
        if (text == null || text.isBlank()) {
            return "";
        }
        return Arrays.stream(text.strip().split("\\R"))
                .map(VerificationReportMarkdown::escapeLine)
                .collect(Collectors.joining("<br>"));
    }

    /** Text that may span paragraphs: escaped, with each line break kept as a hard line break. */
    private static String paragraphs(String text) {
        return Arrays.stream(text.strip().split("\\R"))
                .map(line -> escapeLine(line.stripTrailing()))
                .collect(Collectors.joining("  \n"));
    }

    private static String escapeLine(String line) {
        String escaped = SPECIAL.matcher(line).replaceAll("\\\\$0");
        escaped = EDGE_UNDERSCORE.matcher(escaped).replaceAll("\\\\_");
        Matcher marker = LIST_MARKER.matcher(escaped);
        if (!marker.find()) {
            return escaped;
        }
        String found = marker.group(2);
        String last = found.substring(found.length() - 1);
        return marker.group(1) + found.substring(0, found.length() - 1) + "\\" + last + escaped.substring(marker.end());
    }

    private static String time(Instant instant) {
        return TIME.format(instant);
    }

    private static String label(TaskStatus status) {
        return switch (status) {
            case DRAFT -> "Draft";
            case IN_PROGRESS -> "In progress";
            case APPROVED -> "Approved";
        };
    }

    private static String label(VerificationStatus status) {
        return switch (status) {
            case PENDING -> "Pending";
            case PASSED -> "Passed";
            case FAILED -> "Failed";
        };
    }

    private static String label(VerificationType type) {
        return switch (type) {
            case REQUIREMENTS -> "Requirements";
            case FUNCTIONALITY -> "Functionality";
            case TESTING -> "Testing";
            case ARCHITECTURE -> "Architecture";
            case CODE_QUALITY -> "Code quality";
            case SECURITY -> "Security";
        };
    }

    private static String label(AuditEventType type) {
        return switch (type) {
            case TASK_CREATED -> "Task created";
            case TASK_EDITED -> "Task edited";
            case TASK_STARTED -> "Task started";
            case ARTIFACT_RECORDED -> "Artifact recorded";
            case TEST_RESULTS_RECORDED -> "Test results recorded";
            case CHECK_PASSED -> "Check passed";
            case CHECK_FAILED -> "Check failed";
            case CHECKS_RESET -> "Checks reset";
            case APPROVAL_RECORDED -> "Approval recorded";
            case TASK_APPROVED -> "Task approved";
            case TASK_REOPENED -> "Task reopened";
        };
    }
}
